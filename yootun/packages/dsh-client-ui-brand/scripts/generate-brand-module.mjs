/**
 * 从 yootun/brand/brand.json 生成 src/client/brand-constants.ts（构建期品牌字样单一来源，
 * 避免客户端代码散落硬编码）。素材本体走 `src/client/assets/` 由 tsdown 发射为 lib/assets URL。
 * 运行：`node yootun/packages/dsh-client-ui-brand/scripts/generate-brand-module.mjs`。
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const brandConfig = JSON.parse(readFileSync(resolve(packageRoot, '../../../yootun/brand/brand.json'), 'utf8'))

const module = [
  '/** Generated by scripts/generate-brand-module.mjs from yootun/brand/brand.json. Do not edit directly. */',
  '',
  `export const BRAND_EYEBROW = ${JSON.stringify(brandConfig.eyebrow)}`,
  '',
].join('\n')

writeFileSync(join(packageRoot, 'src', 'client', 'brand-constants.ts'), module)
console.log(`generate-brand-module: brand-constants.ts 已生成（eyebrow=${brandConfig.eyebrow}）`)
