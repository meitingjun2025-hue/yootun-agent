/**
 * 从 `yootun/brand/brand.json` 生成 `src/access-constants.ts`（host 与 client
 * 两半共用的构建期常量）：激活契约版本单一来源（分册 03 C 部分）与租户身份。
 * 版本走构建环境 define（`YOOTUN_BRAND_VALIDATION_VERSION`，由
 * yootun/scripts/brand-environment.mjs 注入、packages/client/tsdown.client.ts
 * 内联），官方构建链不注入该环境时使用文件内缺省——缺省值与 brand.json 当前
 * 值保持一致。运行：`node scripts/generate-access-constants.mjs`（package.json
 * build 已前置）。
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const brandRoot = join(packageRoot, '../../../yootun/brand')
const brandConfig = JSON.parse(readFileSync(join(brandRoot, 'brand.json'), 'utf8'))

// 激活契约版本必须是整数：门禁判定做精确相等比较，非整数在这里 fail loud
// （misconfiguration fails loud at the earliest resolvable point）。
if (!Number.isInteger(brandConfig.validationVersion)) {
  throw new Error(`brand.json validationVersion must be an integer, got ${JSON.stringify(brandConfig.validationVersion)}`)
}

const banner = `/** Generated by scripts/generate-access-constants.mjs from yootun/brand/brand.json. Do not edit directly. */\n`
const body = `
/** 激活契约版本（分册 03 决策点 4）：门禁判定与激活写入共用的唯一字面量，值来自品牌环境。 */
export const VALIDATION_VERSION = process.env.YOOTUN_BRAND_VALIDATION_VERSION ?? '${String(brandConfig.validationVersion)}'

/** 网关租户身份：转发头与租户校验的单一来源。 */
export const TENANT = '${brandConfig.tenant}'
export const TENANT_ID = '${brandConfig.tenantId}'

/** 激活设置 namespace（= bundle patch 的 entry id，host 半 Config schema 暴露）。 */
export const ACCESS_NAMESPACE = 'yootun-access'

/** 托管模型凭证引用：llm-deepseek patch 的 apiKeyEnv 与 credential store 共用此名。 */
export const ACCESS_CREDENTIAL_REF = 'MODELS_API_KEY'

/** 同源激活 API 路由（host 半 webServer 路由，client 同源相对路径调用）。 */
export const ACCESS_VALIDATE_PATH = '/api/desktop/dofe/validate'
export const ACCESS_MODELS_PATH = '/api/desktop/dofe/models'

/** 表单请求共享的有界超时（毫秒）。 */
export const REQUEST_TIMEOUT_MS = 30_000

/** 品牌强调色两档（分册 05 §2）：亮色主题用 primary，暗色主题提亮一档用 primaryDark。 */
export const BRAND_PRIMARY_LIGHT = '${brandConfig.palette.primary}'
export const BRAND_PRIMARY_DARK = '${brandConfig.palette.primaryDark}'
`

writeFileSync(join(packageRoot, 'src/access-constants.ts'), `${banner}${body}`, { mode: 0o644 })

// 门禁 header 的品牌 mark（分册 05 §3.3）：官方构建契约要求 asset 属于本包
// （dsh-package-asset 拒绝跨包素材），生成时从素材分区拷入，单一来源仍是 brand/assets。
mkdirSync(join(packageRoot, 'src/client/assets'), { recursive: true })
copyFileSync(join(brandRoot, brandConfig.artwork.sidebarMark), join(packageRoot, 'src/client/assets/sidebar-mark.png'))

process.stdout.write(`access-constants.ts generated (validationVersion=${String(brandConfig.validationVersion)})\n`)
